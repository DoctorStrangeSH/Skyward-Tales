def main() -> int:
    path = ROOT / "data" / "quest_givers.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    missing = [k for k in data if k not in TALK]
    if missing:
        print("not rewritten:", missing)
    for npc_id, talk in TALK.items():
        if npc_id not in data:
            print("unknown npc", npc_id)
            return 1
        entry = data[npc_id]
        for key in ("idle", "busy"):
            if key in talk:
                entry[key] = talk[key]
        for quest_id, lines in talk.get("lines", {}).items():
            if quest_id not in entry.get("quests", []):
                print("quest not offered by", npc_id, quest_id)
                return 1
            entry.setdefault("lines", {})[quest_id] = lines
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    def words(x) -> int:
        if isinstance(x, str):
            return len(x.split())
        if isinstance(x, dict):
            return sum(words(v) for v in x.values())
        if isinstance(x, list):
            return sum(words(v) for v in x)
        return 0
    print(f"{len(TALK)} NPCs, {words(TALK)} words")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
